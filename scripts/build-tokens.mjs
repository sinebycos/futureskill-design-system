// Generates src/styles/tokens.css and src/tokens/generated.ts from tokens/tokens.json.
// tokens.json is the design-system source (same file the Claude design system uses). Run: npm run tokens
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const t = JSON.parse(readFileSync(resolve(root, 'tokens/tokens.json'), 'utf8'));
const themes = t.color.themes.map((x) => x.id);
const [first] = themes;
const val = (tok, theme) => (typeof tok.value === 'string' ? tok.value : tok.value[theme] ?? tok.value[first]);
const css = (v) => (v.startsWith('{') ? `var(--${v.slice(1, -1)})` : v);
const byName = new Map(t.color.tokens.map((x) => [x.name, x]));
const resolveColor = (name, theme, depth = 0) => {
  if (depth > 16) throw new Error('alias chain too deep: ' + name);
  const v = val(byName.get(name), theme);
  return v.startsWith('{') ? resolveColor(v.slice(1, -1), theme, depth + 1) : v;
};

const decl = (pairs) => pairs.map(([k, v]) => `  --${k}: ${v};`).join('\n');
const light = t.color.tokens.map((x) => [x.name, css(val(x, first))]);
const darkOnly = t.color.tokens.filter((x) => typeof x.value === 'object' && x.value.dark && x.value.dark !== x.value[first]).map((x) => [x.name, css(x.value.dark)]);
const shadows = t.shadow.tokens.map((x) => [x.name, typeof x.value === 'string' ? x.value : x.value[first]]);
const scalars = [...t.spacing.tokens, ...t.radius.tokens, ...t.layout.tokens].map((x) => [x.name, x.value]);
const families = Object.entries(t.type.families).map(([k, v]) => [`font-${k}`, v]);

let out = `/* Generated by scripts/build-tokens.mjs from tokens/tokens.json. Do not edit by hand. */

/* Light is the default. Set data-theme="dark" on <html> for dark, or data-theme="system" to follow the OS. */
:root,
[data-theme="light"] {
${decl(light)}
${decl(shadows)}
}

[data-theme="dark"] {
  color-scheme: dark;
${decl(darkOnly)}
}

@media (prefers-color-scheme: dark) {
  [data-theme="system"] {
    color-scheme: dark;
${decl(darkOnly).replace(/^/gm, '  ')}
  }
}

:root {
${decl(scalars)}
${decl(families)}
}

/* Text styles: Thai (th-*) and English (en-*) */
`;
const styles = [];
for (const g of t.type.groups) for (const s of g.styles) {
  const fam = s.family || g.family;
  styles.push({ ...s, family: fam, group: g.name });
  out += `.${s.name} { font-family: var(--font-${fam}); font-size: ${s.fontSize}; font-weight: ${s.fontWeight};${s.lineHeight !== undefined ? ` line-height: ${s.lineHeight};` : ''} }\n`;
}
writeFileSync(resolve(root, 'src/styles/tokens.css'), out);

const q = (s) => JSON.stringify(s);
const colorNames = t.color.tokens.map((x) => x.name);
const semantic = colorNames.filter((n) => /^(text|stroke|icon|fill|background)-/.test(n));
let ts = `// Generated by scripts/build-tokens.mjs from tokens/tokens.json. Do not edit by hand.

export const themes = ${q(themes)} as const;
export type Theme = (typeof themes)[number];

/** Every colour token. Semantic tokens (text-, stroke-, icon-, fill-, background-) are the ones to build with. */
export const colorTokens = ${q(colorNames)} as const;
export type ColorToken = (typeof colorTokens)[number];

export const semanticColorTokens = ${q(semantic)} as const;
export type SemanticColorToken = (typeof semanticColorTokens)[number];

/** Resolved hex per theme, for places CSS variables cannot reach (canvas, email, OG images). */
export const colorValues: Record<ColorToken, Record<Theme, string>> = {
${colorNames.map((n) => `  ${q(n)}: { ${themes.map((th) => `${th}: ${q(resolveColor(n, th))}`).join(', ')} },`).join('\n')}
};

export const colorUsage: Partial<Record<ColorToken, string>> = {
${t.color.tokens.filter((x) => semantic.includes(x.name)).map((x) => `  ${q(x.name)}: ${q(x.usage)},`).join('\n')}
};

export const spacing = { ${t.spacing.tokens.map((x) => `${q(x.name)}: ${q(x.value)}`).join(', ')} } as const;
export type SpacingToken = keyof typeof spacing;

export const radius = { ${t.radius.tokens.map((x) => `${q(x.name)}: ${q(x.value)}`).join(', ')} } as const;
export type RadiusToken = keyof typeof radius;

export const shadow = {
${t.shadow.tokens.map((x) => `  ${q(x.name)}: ${q(typeof x.value === 'string' ? x.value : x.value[first])},`).join('\n')}
} as const;
export type ShadowToken = keyof typeof shadow;

export const layout = { ${t.layout.tokens.map((x) => `${q(x.name)}: ${q(x.value)}`).join(', ')} } as const;
export type LayoutToken = keyof typeof layout;

export const fontFamilies = ${q(t.type.families)} as const;
export type FontFamilyKey = keyof typeof fontFamilies;

export interface TextStyle { name: string; group: string; family: FontFamilyKey; fontSize: string; fontWeight: number; lineHeight?: string | number }
export const textStyles = ${JSON.stringify(styles.map(({ name, group, family, fontSize, fontWeight, lineHeight }) => ({ name, group, family, fontSize, fontWeight, ...(lineHeight !== undefined ? { lineHeight } : {}) })), null, 1)} as const satisfies readonly TextStyle[];
export type TextStyleName = (typeof textStyles)[number]['name'];
`;
writeFileSync(resolve(root, 'src/tokens/generated.ts'), ts);
console.log(`tokens: ${colorNames.length} colours (${semantic.length} semantic, ${darkOnly.length} with a dark value), ${t.spacing.tokens.length} spacing, ${t.radius.tokens.length} radius, ${t.shadow.tokens.length} shadow, ${styles.length} text styles`);
