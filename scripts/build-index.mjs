// Regenerates src/index.ts from the component folders, in gallery order. Run after adding a component.
import { readdirSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const ORDER = ['Button', 'TextLink', 'TextInput', 'Checkbox', 'Toggle', 'Slider', 'SegmentedControl', 'Tabs', 'NavigationSide', 'Stepper', 'Alert', 'Toast', 'Badge', 'OjtMethodBadge', 'NotiItem', 'ProgressBar', 'SkillProgress', 'SkillGraph', 'SkillLevel', 'SectionTypeItem', 'SectionTypeDescription', 'OutsideLearningCard', 'TestSelectionCard', 'SurveySelectionCard', 'Input', 'SearchBox', 'PasswordInput', 'Textarea'];
const dir = resolve(root, 'src/components');
const comps = readdirSync(dir).filter((d) => existsSync(resolve(dir, d, 'index.ts')));
comps.sort((a, b) => (ORDER.indexOf(a) + 1 || 999) - (ORDER.indexOf(b) + 1 || 999) || a.localeCompare(b));
const out = `// Generated by scripts/build-index.mjs. Do not edit by hand.
import './styles/index.css';

export { cx } from './utils/cx';
export { cssVar } from './tokens';
export type { ColorToken, SemanticColorToken, SpacingToken, RadiusToken, ShadowToken, TextStyleName, Theme } from './tokens';

${comps.map((c) => `export * from './components/${c}';`).join('\n')}
`;
writeFileSync(resolve(root, 'src/index.ts'), out);
console.log('index:', comps.length, 'components');
